// Generates src/api/schema.ts (TypeScript types of the OpenAPI contract) from docs/api/openapi.json.
//   node scripts/generate-api.mjs          write the file
//   node scripts/generate-api.mjs --check  fail (exit 1) when the committed file is not what the contract produces
// The contract is the snapshot the .NET test suite keeps equal to what the service serves at /api/v1/openapi.json.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import openapiTS, { astToString } from 'openapi-typescript'

const here = dirname(fileURLToPath(import.meta.url))
const contract = resolve(here, '../../../docs/api/openapi.json')
const target = resolve(here, '../src/api/schema.ts')

const header = '// GENERATED by scripts/generate-api.mjs from docs/api/openapi.json. Do not edit; run `npm run api:generate`.\n'
const ast = await openapiTS(pathToFileURL(contract), { alphabetize: false })
const generated = header + astToString(ast).replace(/\r\n/g, '\n')

if (process.argv.includes('--check')) {
  let current = ''
  try {
    current = readFileSync(target, 'utf8').replace(/\r\n/g, '\n')
  } catch {
    // missing: stale
  }
  if (current !== generated) {
    console.error('The generated API client (src/api/schema.ts) is stale against docs/api/openapi.json. Run: npm run api:generate')
    process.exit(1)
  }
  console.log('The generated API client matches the contract.')
} else {
  writeFileSync(target, generated)
  console.log('Wrote src/api/schema.ts')
}
